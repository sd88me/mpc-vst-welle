#!/usr/bin/env python3
"""vst/params.json (from tools/gen_params.py) -> src/sdk/params_gen.h: the parameter table of the SDK front end (src/sdk/WellePlugin.cpp).
Order = vst/params.json = vst/params.lock (checked): the VST parameter index saved projects and skins bind to. Append only."""
import json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst/params.json")))["params"]
lock = [l.strip() for l in open(os.path.join(ROOT, "vst/params.lock")) if l.strip()]
keys = [p["key"] for p in P]
if keys[:len(lock)] != lock:
    raise SystemExit("params.json no longer starts with params.lock: the order is frozen (append only)")
floats = set(re.findall(r'\{"(\w+)", 1,', open(os.path.join(ROOT, "src/dsp/welle_params.h")).read()))
out = ["/* generated by tools/gen_sdk_params.py: do not edit. One row per parameter, in the frozen VST order. */", "#pragma once",
       "enum { kMomentary = 1, kText = 2, kFloatDisp = 4, kChoice = 8, kUi = 16 };",
       "struct PSpec { const char *key, *name; int min, max, def, flags; const char *const *choices; int nchoices; };", ""]
rows = []
for i, p in enumerate(P):
    fl, ch, n = 0, "nullptr", 0
    if "options" in p:
        fl |= 8
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, opts.index(p["default"])
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
    if p.get("momentary"): fl |= 1
    if p.get("display") == "string": fl |= 2
    if p["key"] in floats: fl |= 4
    rows.append('    {%s, %s, %d, %d, %d, %d, %s, %d},' % (json.dumps(p["key"]), json.dumps(p["name"]), lo, hi, d, fl, ch, n))
rows.append('    {"ui_open", "POPUP", 0, 96, 0, 16, nullptr, 0},   // UI only (kUi): which drawn pick-list is open; appended last, not an engine key')
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};", "static const int kNumParams = %d;" % (len(P) + 1), "static const int kUiParam = %d;" % len(P), ""]
open(os.path.join(ROOT, "src/sdk/params_gen.h"), "w").write("\n".join(out))
print("src/sdk/params_gen.h: %d params" % len(P))
